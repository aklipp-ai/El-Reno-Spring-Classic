/* ================= shared helpers ================= */
const SD = (function(){
  const KEY_DRAFT = 'er_soccer_draft_v3';
  const KEY_PUB   = 'er_soccer_published_v3';
  const KEY_PASS  = 'er_soccer_pass_v1';

  function clone(o){ return JSON.parse(JSON.stringify(o)); }

  function b64e(str){
    return btoa(String.fromCharCode.apply(null, new TextEncoder().encode(str)))
      .replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');
  }
  function b64d(str){
    str = str.replace(/-/g,'+').replace(/_/g,'/');
    while(str.length % 4) str += '=';
    const bin = atob(str);
    const bytes = new Uint8Array(bin.length);
    for(let i=0;i<bin.length;i++) bytes[i] = bin.charCodeAt(i);
    return new TextDecoder().decode(bytes);
  }

  function encode(data){ return b64e(JSON.stringify(data)); }
  function decode(str){
    try{ return JSON.parse(b64d(str)); }catch(e){ return null; }
  }

  function readHash(){
    const m = location.hash.match(/[#&]s=([^&]+)/);
    return m ? decode(m[1]) : null;
  }

  function liveData(){
    try{
      if(typeof window !== 'undefined' && window.PUBLISHED_DATA && window.PUBLISHED_DATA.games){
        return window.PUBLISHED_DATA;
      }
    }catch(e){}
    return null;
  }

  function getDraft(){
    try{
      const raw = localStorage.getItem(KEY_DRAFT);
      if(raw) return JSON.parse(raw);
    }catch(e){}
    const live = liveData();
    return live ? clone(live) : clone(DEFAULT_DATA);
  }
  function saveDraft(d){
    localStorage.setItem(KEY_DRAFT, JSON.stringify(d));
  }
  function getPublished(){
    try{
      const raw = localStorage.getItem(KEY_PUB);
      if(raw) return JSON.parse(raw);
    }catch(e){}
    return null;
  }
  function publish(d){
    localStorage.setItem(KEY_PUB, JSON.stringify(d));
  }
  function getPass(){ return localStorage.getItem(KEY_PASS) || 'elreno'; }
  function setPass(p){ localStorage.setItem(KEY_PASS, p); }

  /* public page data source: shared link > published > default */
  function loadPublic(){
    const h = readHash();
    if(h && h.games) return h;
    const live = liveData();
    if(live) return clone(live);
    const p = getPublished();
    if(p && p.games) return p;
    return clone(DEFAULT_DATA);
  }

  function teamsOf(d){
    const s = new Set();
    d.games.forEach(g=>{ if(g.a) s.add(g.a); if(g.b) s.add(g.b); });
    (d.teams && d.teams.G || []).forEach(t=>s.add(t));
    (d.teams && d.teams.B || []).forEach(t=>s.add(t));
    return Array.from(s).sort((x,y)=>x.localeCompare(y));
  }

  function fieldName(d, id){
    const f = (d.fields||[]).find(f=>f.id===id);
    return f ? f.name : id;
  }
  function fieldLabel(d, id){
    const f = (d.fields||[]).find(f=>f.id===id);
    return f ? (f.name + (f.sub ? ', ' + f.sub : '')) : id;
  }
  function isBlocked(d, fid, time){
    return (d.blocked||[]).some(b=>b[0]===fid && b[1]===time);
  }
  function gamesAt(d, fid, time){
    return d.games.filter(g=>g.field===fid && g.time===time);
  }
  function sortGames(d, list){
    const ti = t => { const i=(d.times||[]).indexOf(t); return i<0?99:i; };
    const fi = f => { const i=(d.fields||[]).findIndex(x=>x.id===f); return i<0?99:i; };
    return list.slice().sort((x,y)=> ti(x.time)-ti(y.time) || fi(x.field)-fi(y.field) || (x.num||0)-(y.num||0));
  }
  function teamGames(d, team, gender){
    return sortGames(d, d.games.filter(g=>
      (g.a===team || g.b===team) && (!gender || g.gender===gender)));
  }
  function opponentOf(g, team){ return g.a===team ? g.b : g.a; }

  /* ---- division helpers (girls and boys are separate pools) ---- */
  function teamKey(gender, name){ return gender + '|' + name; }
  function parseTeamKey(k){
    const i = String(k||'').indexOf('|');
    return i < 0 ? {gender:'', name:String(k||'')}
                 : {gender:k.slice(0,i), name:k.slice(i+1)};
  }
  function divisionOf(d, name){
    if(((d.teams&&d.teams.G)||[]).indexOf(name) > -1) return 'G';
    if(((d.teams&&d.teams.B)||[]).indexOf(name) > -1) return 'B';
    const g = d.games.find(x=>x.a===name || x.b===name);
    return g ? (g.gender||'') : '';
  }
  function teamsIn(d, gender){
    if(gender === 'G' || gender === 'B'){
      const list = (d.teams && d.teams[gender]) || [];
      return Array.from(new Set(list)).sort((a,b)=>a.localeCompare(b));
    }
    return teamsOf(d);
  }
  function divisionFromUrl(){
    const m = (location.search||'').match(/[?&]d=([GB])/i) ||
              (location.hash||'').match(/[#&]d=([GB])/i);
    return m ? m[1].toUpperCase() : '';
  }

  function newId(d){
    let n = 1;
    const ids = new Set(d.games.map(g=>g.id));
    while(ids.has('g'+n)) n++;
    return 'g'+n;
  }

  return {clone,encode,decode,readHash,getDraft,saveDraft,getPublished,publish,liveData,
          getPass,setPass,loadPublic,teamsOf,fieldName,fieldLabel,isBlocked,
          gamesAt,sortGames,teamGames,opponentOf,newId,
          teamKey,parseTeamKey,divisionOf,teamsIn,divisionFromUrl};
})();
